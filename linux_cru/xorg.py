"""The X11 route: an xorg.conf snippet plus the scripts that install it.

This is the path taken on a plain X11 session (and on XWayland, where
it is the only path that reaches the real display server). The
configuration file is a single snippet in /etc/X11/xorg.conf.d/, which
Xorg reads on every start, and an optional patched EDID for the NVIDIA
driver, which needs one from 580.105.08 onwards.

Everything here is generated as text or as a root script, so it can be
inspected before it runs and tested without touching the system.
"""

import glob
import os

from datetime import datetime

XORG_CONF_DIR = "/etc/X11/xorg.conf.d"
XORG_CONF_NAME = "10-linux-cru.conf"
XORG_CONF = f"{XORG_CONF_DIR}/{XORG_CONF_NAME}"

CUSTOMEDID_DIR = "/etc/X11"
CUSTOMEDID_PREFIX = "linux-cru-"

# The ModeValidation flags that let the NVIDIA driver accept modes the
# display does not declare. AllowNonEdidModes on its own still rejects
# out-of-spec modes, so the checks have to be relaxed as well.
NVIDIA_RELAX_FLAGS = (
    "NoEdidMaxPClkCheck",
    "NoMaxPClkCheck",
    "NoMaxSizeCheck",
    "NoHorizSyncCheck",
    "NoVertRefreshCheck",
)


def customedid_path(output):
    """Where the patched EDID for `output` is installed."""
    return f"{CUSTOMEDID_DIR}/{CUSTOMEDID_PREFIX}{output}.bin"


def installed_customedids():
    """Outputs that currently have a patched EDID installed."""
    out = []
    for path in sorted(glob.glob(f"{CUSTOMEDID_DIR}/{CUSTOMEDID_PREFIX}*.bin")):
        name = os.path.basename(path)[len(CUSTOMEDID_PREFIX):-len(".bin")]
        out.append(name)
    return out


def installed():
    """True when this tool has left an xorg.conf snippet behind."""
    return os.path.exists(XORG_CONF)


def build_config(output, name, ml, nvidia=False, relax_validation=False,
                 customedid=None, timestamp=None):
    """The text of the xorg.conf snippet.

    nvidia:            add the Device section with the NVIDIA options.
    relax_validation:  also turn off the EDID limit checks.
    customedid:        path of the patched EDID to point CustomEDID at.
    """
    stamp = timestamp or datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    conf = [f"# Generated by Linux CRU on {stamp}\n",
            'Section "Monitor"\n',
            f'    Identifier "{output}"\n',
            f'    {ml.xorg_modeline(name)}\n',
            f'    Option "PreferredMode" "{name}"\n',
            'EndSection\n']
    if nvidia:
        flags = ["AllowNonEdidModes"]
        if relax_validation:
            flags += NVIDIA_RELAX_FLAGS
        device = ['\nSection "Device"\n',
                  '    Identifier "LinuxCRU-nvidia"\n',
                  '    Driver "nvidia"\n',
                  f'    Option "Monitor-{output}" "{output}"\n',
                  f'    Option "ModeValidation" "{", ".join(flags)}"\n',
                  '    Option "ModeDebug" "true"\n']
        if customedid:
            device.append(f'    Option "CustomEDID" "{output}:{customedid}"\n')
        device.append('EndSection\n')
        conf += device
    return "".join(conf)


def build_install_script(conf_source, customedid_source=None,
                         customedid_target=None):
    """Root script: install the snippet (and the patched EDID).

    The sources are files this tool has already written; the script only
    copies them into place, so nothing is generated inside the script
    that could go wrong with quoting.
    """
    lines = ["#!/bin/bash\n",
             "# linux-cru: install the X11 configuration\n",
             "set -e\n",
             f"mkdir -p '{XORG_CONF_DIR}'\n",
             f"install -m 644 '{conf_source}' '{XORG_CONF}'\n",
             f"echo \"installed {XORG_CONF}\"\n"]
    if customedid_source and customedid_target:
        lines += [f"install -m 644 '{customedid_source}' '{customedid_target}'\n",
                  f"echo \"installed {customedid_target}\"\n"]
    return "".join(lines)


def build_uninstall_script(output=None):
    """Root script: remove the snippet and any patched EDID.

    With an output name only that output's EDID goes; without one
    every file this tool installed is removed.
    """
    if output:
        target = customedid_path(output)
        removal = [f"rm -f '{target}'\n",
                   f"echo \"removed {target}\"\n"]
    else:
        removal = [f"rm -f '{CUSTOMEDID_DIR}'/{CUSTOMEDID_PREFIX}*.bin\n",
                   "echo \"removed the patched EDID files\"\n"]
    return f"""#!/bin/bash
# linux-cru: remove the X11 configuration
set -e
rm -f '{XORG_CONF}'
echo "removed {XORG_CONF}"
{''.join(removal)}
"""
